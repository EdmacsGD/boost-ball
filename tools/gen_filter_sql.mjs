// Writes the database copy of the word filter (bb_bad_word) from src/meta/wordFilter.js.
// Usage: node tools/gen_filter_sql.mjs > supabase/filter_function.sql
import { ANYWHERE, WORDS, CODES, FROM, TO } from '../src/meta/wordFilter.js';
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const pat = (w) => w.split('').map((c) => `${c}+`).join('');
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;
const single = WORDS.filter((w) => !w.includes(' '));
const multi = WORDS.filter((w) => w.includes(' '));
console.log(`-- Generated by tools/gen_filter_sql.mjs from src/meta/wordFilter.js. Do not edit by hand.
-- Returns the first bad word found in t (same rules as the game), or null.
create or replace function public.bb_bad_word(t text) returns text
language plpgsql immutable set search_path = '' as $$
declare
  raw text := lower(coalesce(t, ''));
  n text;
  toks text[];
  cands text[];
  run text := '';
  tok text;
  w text;
  spaced text;
  i int;
begin
  foreach w in array ${arr(CODES)} loop
    if position(w in raw) > 0 then return w; end if;
  end loop;
  n := replace(translate(raw, ${q(FROM)}, ${q(TO)}), 'æ', 'ae');
  toks := array_remove(regexp_split_to_array(n, '[^a-z]+'), '');
  cands := toks;
  foreach tok in array toks loop
    if length(tok) = 1 then
      run := run || tok;
    else
      if length(run) > 1 then cands := cands || run; end if;
      run := '';
    end if;
  end loop;
  if length(run) > 1 then cands := cands || run; end if;
  for i in 1 .. ${ANYWHERE.length} loop
    if exists (select 1 from unnest(cands) c where c ~ (${arr(ANYWHERE.map(pat))})[i]) then return (${arr(ANYWHERE)})[i]; end if;
  end loop;
  for i in 1 .. ${single.length} loop
    if exists (select 1 from unnest(cands) c where c ~ (${arr(single.map((w) => `^${pat(w)}$`))})[i]) then return (${arr(single)})[i]; end if;
  end loop;
  spaced := ' ' || array_to_string(toks, ' ') || ' ';
  foreach w in array ${arr(multi)} loop
    if position(' ' || w || ' ' in spaced) > 0 then return w; end if;
  end loop;
  return null;
end $$;`);
